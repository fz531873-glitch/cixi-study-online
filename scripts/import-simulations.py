def main():
    seed = json.loads((ROOT / 'data/catalog.json').read_text(encoding='utf-8'))
    incoming = json.loads(SOURCE.read_text(encoding='utf-8'))
    originals = {q['id']: q for q in seed['questions']}
    assignments = {}
    for source_ids, knowledge_ids in GROUPS:
        assert len(source_ids) == len(knowledge_ids)
        assignments.update(zip(source_ids, knowledge_ids))
    assert len(incoming) == len(assignments) == 190
    assert set(assignments) == {q['id'] for q in seed['questions'] if q['type'] == '单选'}
    knowledge = []
    for kid, category, title, body, prompt, source in SUPPLEMENTS:
        assert category in {k['category'] for k in seed['knowledge']}
        knowledge.append(dict(id=kid,category=category,chapter=title,title=title,content=body,
            question=prompt,source=source,module='模拟题补充知识',status='待核对',
            material=11,page=1,version=1))
    known = {k['id']:k for k in seed['knowledge'] + knowledge}
    assert len(known) == len(seed['knowledge']) + len(knowledge)
    display = {'经济学':'经济','管理学':'管理','马克思主义原理':'马原'}
    questions, links = [], []
    counts = Counter()
    for q in incoming:
        original = originals[q['source_id']]
        kid = assignments[q['source_id']]
        k = known[kid]
        category = k['category']
        counts[category] += 1
        qid = 500000 + int(q['id'].split('M')[1])
        body = q['stem'] + '\n' + '\n'.join(f'{letter}. {value}' for letter,value in q['options'].items())
        note = f'新编模拟题{q["id"]}，非历年真题。参照{q["source_exam"]}第{q["source_number"]}题。'
        if q['note']:
            note += q['note']
        questions.append(dict(id=qid,exam='模拟题 · '+display.get(category,category),number=counts[category],
            type='单选',body=body,answer=q['answer'],analysis=q['analysis'],direct=q['analysis'],
            source_page=original['source_page'],analysis_page=original['analysis_page'],
            question_material=original['question_material'],analysis_material=original['analysis_material'],
            status='待核对',note=note,references=[],image='',version=1,
            explanation_source='新编模拟题 · 逐项解析（未试测）',kind='模拟题',
            simulation_id=q['id'],template_question_id=q['source_id'],category=category,topic=q['topic']))
        links.append(dict(knowledge_id=kid,question_id=qid,status='已确认',role='主考点',
            position='题干与解析',reason=f'人工归类：{q["topic"]}，对应知识点“{k["title"]}”。',
            evidence=f'{q["id"]}题干与逐项解析；参照{q["source_exam"]}第{q["source_number"]}题'))
    assert len({q['id'] for q in questions}) == 190
    assert not set(originals).intersection(q['id'] for q in questions)
    assert all(len(q['answer']) == 1 and q['answer'] in 'ABCD' for q in questions)
    assert all(link['knowledge_id'] in known for link in links)
    assert all(any(l['knowledge_id'] == k['id'] for l in links) for k in knowledge)
    output = dict(generated=DAY,questions=questions,knowledge=knowledge,links=links)
    path = ROOT / 'data/simulations.json'
    path.write_text(json.dumps(output,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    assert json.loads(path.read_text(encoding='utf-8')) == output
    lines = ['# 模拟题分类导入记录', '', f'日期：{DAY}。导入190道模拟题，沿用现有15个大类；补充{len(knowledge)}张配套知识卡。',
        '原catalog.json中的345道原题、196张原知识卡保持独立。新增模拟题ID为500001—500190，原NB-M编号保留。',
        '模拟题统一标为待核对，已确认的关联仅表示人工核对了考点分类，不表示经过考生试测。', '',
        '|大类|模拟题数|','|---|---:|']
    lines.extend(f'|{display.get(c,c)}|{n}|' for c,n in sorted(counts.items()))
    lines += ['', '|模拟题编号|系统ID|细分考点|大类|知识卡ID|知识卡标题|', '|---|---:|---|---|---:|---|']
    by_id = {q['id']:q for q in questions}
    for link in links:
        q, k = by_id[link['question_id']], known[link['knowledge_id']]
        lines.append(f'|{q["simulation_id"]}|{q["id"]}|{q["topic"]}|{display.get(k["category"],k["category"])}|{k["id"]}|{k["title"]}|')
    (ROOT / '模拟题分类导入_20261106.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps({'questions':len(questions),'supplemental_knowledge':len(knowledge),'links':len(links),'categories':counts},ensure_ascii=False))


if __name__ == '__main__':
    main()
